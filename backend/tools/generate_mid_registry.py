#!/usr/bin/env python3
from pathlib import Path
import argparse, hashlib, json, re, zipfile, fnmatch, subprocess

def locate(root, patterns, expected):
    for p in sorted(Path(root).glob('*.zip')):
        if not any(fnmatch.fnmatch(p.name,x) for x in patterns): continue
        if hashlib.sha256(p.read_bytes()).hexdigest()==expected: return p
    raise SystemExit('current src_64 oracle not found by verified hash')

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--root',default='/mnt/data');ap.add_argument('--check',action='store_true');a=ap.parse_args()
    repo=Path(__file__).resolve().parents[1]
    lock=json.loads((repo/'oracles.lock.json').read_text())
    o=next(x for x in lock['oracles'] if x['id']=='current_src64')
    z=locate(a.root,o['filename_patterns'],o['sha256'])
    path='app-assets/output/assets/src_64/app/common/network/mid.lua'
    with zipfile.ZipFile(z) as zz: raw=zz.read(path)
    text=raw.decode('utf-8-sig'); sha=hashlib.sha256(raw).hexdigest(); assignments=[]; by={}
    for i,line in enumerate(text.splitlines(),1):
        m=re.search(r'xyd\.mid\.([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(\d+)',line)
        if m:
            s=m.group(1);n=int(m.group(2));assignments.append({'symbol':s,'mid':n,'line':i});by.setdefault(n,[]).append(s)
    facts={'schema_version':1,'pass':'435.0','stage':'I2','source':'current src_64 app/common/network/mid.lua','source_sha256':sha,'assignment_count':len(assignments),'unique_numeric_mid_count':len(by),'classification_source':{'chat':'bit.band(mid,36864)==32768','gm':'bit.band(mid,36864)==36864','other':'Backend.request -> webRequest_'},'assignments':assignments}
    facts_text=json.dumps(facts,indent=2)+'\n'
    lines=[]
    for n in sorted(by):
        vals=[]
        for s in by[n]:
            if s not in vals: vals.append(s)
        lines.append(f'\t{n}: {{{", ".join(json.dumps(s) for s in vals)}}},')
    go='// Code generated by tools/generate_mid_registry.py; DO NOT EDIT.\npackage mids\n\n'+f'const CurrentSourceSHA256 = {json.dumps(sha)}\nconst CurrentAssignmentCount = {len(assignments)}\nconst CurrentUniqueMIDCount = {len(by)}\n\nvar sourceAliases = map[uint16][]string{{\n'+ '\n'.join(lines)+'\n}\n'
    go=subprocess.run(['gofmt'],input=go.encode(),stdout=subprocess.PIPE,check=True).stdout.decode()
    targets=[(repo/'testdata/sourcefacts/pass435_current_mid_assignments.json',facts_text),(repo/'internal/protocol/mids/registry_gen.go',go)]
    if a.check:
        bad=[]
        for p,s in targets:
            if not p.exists() or p.read_text()!=s: bad.append(str(p.relative_to(repo)))
        if bad: raise SystemExit('MID registry drift: '+', '.join(bad))
        print(f'MID REGISTRY: PASS source_sha256={sha} assignments={len(assignments)} unique={len(by)}');return
    for p,s in targets:p.parent.mkdir(parents=True,exist_ok=True);p.write_text(s)
    print('generated MID registry')
if __name__=='__main__':main()
