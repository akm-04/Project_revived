#!/usr/bin/env python3
from pathlib import Path
import argparse,hashlib,re,sys
root=Path(__file__).resolve().parents[1]
src=root/'sql/kernel/receipts.sql'
out=root/'internal/adapters/postgres/kernelqueries/querytext_gen.go'

def render():
    text=src.read_text()
    pat=re.compile(r'^-- name:\s+([A-Za-z0-9_]+)\s+:[a-z]+\s*\n',re.M)
    matches=list(pat.finditer(text))
    if not matches: raise SystemExit('no named queries')
    parts=[]
    for i,m in enumerate(matches):
        end=matches[i+1].start() if i+1<len(matches) else len(text)
        sql=text[m.end():end].strip()
        parts.append((m.group(1),sql))
    sha=hashlib.sha256(text.encode()).hexdigest()
    lines=['// Code generated by tools/generate_kernel_querytext.py; DO NOT EDIT.','package kernelqueries','','// SourceSHA256 is the exact owner query-source hash.','const SourceSHA256 = "'+sha+'"','']
    for name,sql in parts:
        lines += [f'const {name} = `'+sql.replace('`','`+"`"+`')+'`','']
    return '\n'.join(lines),sha

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--check',action='store_true')
    a=ap.parse_args()
    rendered,sha=render()
    if a.check:
        if not out.exists() or out.read_text()!=rendered:
            print(f'KERNEL QUERYTEXT: FAIL stale {out.relative_to(root)} for {src.relative_to(root)} sha256={sha}')
            return 1
        print(f'KERNEL QUERYTEXT: PASS sha256={sha}')
        return 0
    out.parent.mkdir(parents=True,exist_ok=True)
    out.write_text(rendered)
    print(f'generated {out.relative_to(root)} from {src.relative_to(root)} sha256={sha}')
    return 0
if __name__=='__main__': sys.exit(main())
