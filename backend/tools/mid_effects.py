#!/usr/bin/env python3
"""Derive each registered MID's effect (read, state, unknown) for reply replay.

The source is the system map's per-MID trace class (docs/architecture/system_map/MID_CLASSES.json).
Its `writes` value is `state` when the route trace reaches write SQL other than the receipt store,
`receipt` when it records only an operation receipt, `none` when the walk found no write, and
`UNKNOWN` when a FANOUT, UNRESOLVED or BOUND marker could hide one. `none` is a trace-backed read:
only a complete walk with no marker and at least one traced transaction yields it; an empty trace is
`unknown`, because a typed service port the map does not follow hides its writes (A-062). Lock clauses do not raise a MID above its write
class here: route traces show only the shared session FOR SHARE or conditional FOR UPDATE clauses
whose caller argument decides, so they are not proof of a change.

An `unknown` MID counts as `state` for undelivered-reply replay, because a wrong `state` only
clears a stored mark early.

--write also emits internal/protocol/mids/effects_gen.go (the read set the edge consults), and
--check fails when either artifact is stale.
"""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MID_CLASSES = ROOT / "docs" / "architecture" / "system_map" / "MID_CLASSES.json"
OUTPUT = ROOT / "docs" / "protocol" / "MID_EFFECTS.json"
OUTPUT_GO = ROOT / "internal" / "protocol" / "mids" / "effects_gen.go"

WRITE_EFFECTS = {"state": "state", "receipt": "state", "none": "read"}

# Routes whose trace reaches no transaction at all, so an empty transaction list
# cannot decide them. Both are proved pure reads in the source and by contract:
# MID 3 returns only the request-time server_time (projection/lobby/shapes.go
# Explicit, I9_11D_COMPAT_V2 C10) and MID 279 returns the constant F4e terminal
# without locking or settling (I9_11D_COMPAT_V2 C7). Replaying either from a
# stored reply would move client countdowns or repeat a terminal.
PURE_READ_MIDS = {
    3: "I9_11D_COMPAT_V2 C10 read-only server_time",
    279: "I9_11D_COMPAT_V2 C7 terminal settles nothing",
}

# Routes the trace cannot decide (their transaction flags are arguments) but
# whose handler is a read by construction. MID 37 lists the served shops through
# Service.List, whose transaction is read-only and which records no receipt
# (application/shop/commands.go List -> run readOnly=true, service.go run
# ReadOnly: readOnly). MID 38 is not here: closing a temp shop is a write route
# (I9_11C_CORE_SHOPS_V2 C11), so it stays state.
EVIDENCE_READ_MIDS = {
    37: "I9_11C_CORE_SHOPS_V2 C4/C12 read-only shop list",
}


def json_text(value):
    return json.dumps(value, indent=1, ensure_ascii=False, sort_keys=True) + "\n"


def go_text(document):
    reads = sorted(row["mid"] for row in document["mids"] if row["effect"] == "read")
    lines = [
        "// Code generated by tools/mid_effects.py --write; DO NOT EDIT.",
        "package mids",
        "",
        "// readMIDs is the trace-backed read set of docs/protocol/MID_EFFECTS.json.",
        "// An unlisted MID counts as state-changing for undelivered-reply replay.",
        "var readMIDs = map[uint16]struct{}{",
    ]
    width = max((len("%d:" % mid) for mid in reads), default=0)
    for mid in reads:
        key = "%d:" % mid
        lines.append("\t%s%s{}," % (key, " " * (width - len(key) + 1)))
    lines += [
        "}",
        "",
        "// StateChanging reports whether a MID may change durable state. An unknown",
        "// effect counts as state, because a wrong state only clears a mark early.",
        "func StateChanging(mid uint16) bool {",
        "\t_, read := readMIDs[mid]",
        "\treturn !read",
        "}",
        "",
    ]
    return "\n".join(lines)


def load_mid_classes(path=None):
    source = path or MID_CLASSES
    try:
        return json.loads(source.read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise SystemExit("missing %s; run tools/system_map.py --write" % source)


def mid_effect(row):
    if row.get("mid") in EVIDENCE_READ_MIDS:
        return "read"
    if row.get("state_writes") or row.get("receipt_writes"):
        return "state"
    if row.get("mid") in PURE_READ_MIDS:
        return "read"
    if not row.get("transactions"):
        return "unknown"
    return WRITE_EFFECTS.get(row.get("writes"), "unknown")


def effect_document(mid_classes):
    rows = mid_classes.get("mids")
    if not isinstance(rows, list) or not rows:
        raise SystemExit("MID_CLASSES.json has no mids")
    effects = []
    seen = set()
    for row in rows:
        mid = row.get("mid")
        if not isinstance(mid, int) or mid in seen:
            raise SystemExit("MID class has a missing or duplicate mid: %r" % (mid,))
        seen.add(mid)
        effects.append({"mid": mid, "effect": mid_effect(row)})
    effects.sort(key=lambda effect: effect["mid"])
    return {
        "generated_by": "tools/mid_effects.py --write",
        "source": "docs/architecture/system_map/MID_CLASSES.json",
        "note": "read = a traced transaction reached no write; state = it reached a write (a receipt "
                "included); unknown = the trace could not decide or had no transaction, and counts as "
                "state for undelivered-reply replay.",
        "mids": effects,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    document = effect_document(load_mid_classes())
    if arguments.write:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(json_text(document), encoding="utf-8")
        OUTPUT_GO.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT_GO.write_text(go_text(document), encoding="utf-8")
        print("wrote %s" % OUTPUT)
        print("wrote %s" % OUTPUT_GO)
        return 0
    stale = False
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
    if current != json_text(document):
        print("stale: %s" % OUTPUT)
        stale = True
    current_go = OUTPUT_GO.read_text(encoding="utf-8") if OUTPUT_GO.is_file() else ""
    if current_go != go_text(document):
        print("stale: %s" % OUTPUT_GO)
        stale = True
    if stale:
        return 1
    print("MID effects are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
