"use strict";

import { actionButton, createModal, errorParagraph } from "./modal.js";

const maximumReasonLength = 500;

// confirmAction returns {reason, semantic_key} or null on cancel. The reason is
// required (owner asked to keep it); the semantic key is GUI-generated and
// lives under the Advanced details fold.
export function confirmAction(options) {
  const settings = options || {};
  const semanticKey = newSemanticKey();
  return new Promise((resolve) => {
    let settled = false;
    function settle(value) {
      if (settled) {
        return;
      }
      settled = true;
      resolve(value);
    }
    const dialog = createModal({
      title: settings.title || "Confirm action",
      modalId: "confirm-action",
      onClose: () => settle(null),
    });
    if (settings.summary) {
      const summary = document.createElement("p");
      summary.className = "confirm-summary";
      summary.textContent = settings.summary;
      dialog.body.append(summary);
    }
    const reasonLabel = document.createElement("label");
    reasonLabel.className = "form-label";
    reasonLabel.htmlFor = "confirm-reason";
    reasonLabel.textContent = "Reason (required)";
    const reasonInput = document.createElement("input");
    reasonInput.type = "text";
    reasonInput.className = "form-control";
    reasonInput.id = "confirm-reason";
    reasonInput.maxLength = maximumReasonLength;
    reasonInput.autocomplete = "off";
    const advanced = document.createElement("details");
    advanced.className = "confirm-advanced";
    advanced.id = "confirm-advanced";
    const advancedSummary = document.createElement("summary");
    advancedSummary.textContent = "Advanced details";
    const keyHint = document.createElement("p");
    keyHint.className = "hint mb-1";
    keyHint.textContent = "Semantic key (generated by the GUI, used for idempotency):";
    const keyValue = document.createElement("code");
    keyValue.id = "confirm-semantic-key";
    keyValue.textContent = semanticKey;
    advanced.append(advancedSummary, keyHint, keyValue);
    const failure = errorParagraph();
    dialog.body.append(reasonLabel, reasonInput, advanced, failure);

    const cancel = actionButton("Cancel", false, "confirm-cancel");
    const confirm = actionButton(settings.confirmLabel || "Confirm", true, "confirm-submit");
    reasonInput.addEventListener("keydown", (event) => {
      if (event.key === "Enter") {
        event.preventDefault();
        confirm.click();
      }
    });
    cancel.addEventListener("click", () => dialog.close());
    confirm.addEventListener("click", () => {
      const reason = reasonInput.value.trim();
      if (reason === "") {
        failure.textContent = "A reason is required.";
        return;
      }
      if (reason.length > maximumReasonLength) {
        failure.textContent = "The reason must hold at most " + maximumReasonLength + " characters.";
        return;
      }
      settle({ reason, semantic_key: semanticKey });
      dialog.close();
    });
    dialog.footer.append(cancel, confirm);
    reasonInput.focus();
  });
}

function newSemanticKey() {
  if (window.crypto && typeof window.crypto.randomUUID === "function") {
    return window.crypto.randomUUID();
  }
  const bytes = new Uint8Array(16);
  window.crypto.getRandomValues(bytes);
  return Array.from(bytes, (value) => value.toString(16).padStart(2, "0")).join("");
}
