#!/usr/bin/env python3
from pathlib import Path
import argparse,hashlib,re,sys
root=Path(__file__).resolve().parents[1]
sources=[root/'sql/character/hero.sql',root/'sql/character/pet.sql',root/'sql/character/preset.sql',root/'sql/character/practice.sql']
out=root/'internal/adapters/postgres/characterqueries/querytext_gen.go'
def parse(src):
    text=src.read_text(); pat=re.compile(r'^-- name:\s+([A-Za-z0-9_]+)\s+:[a-z]+\s*\n',re.M); ms=list(pat.finditer(text))
    if not ms: raise SystemExit(f'no named character queries in {src.relative_to(root)}')
    parts=[]
    for i,m in enumerate(ms):
        end=ms[i+1].start() if i+1<len(ms) else len(text); parts.append((m.group(1),text[m.end():end].strip()))
    return text,parts
def render():
    parsed=[(src,*parse(src)) for src in sources]
    seen=set(); parts=[]
    for src,text,rows in parsed:
        for name,sql in rows:
            if name in seen: raise SystemExit(f'duplicate character query {name}')
            seen.add(name); parts.append((name,sql))
    hero_sha=hashlib.sha256(parsed[0][1].encode()).hexdigest()
    pet_sha=hashlib.sha256(parsed[1][1].encode()).hexdigest()
    preset_sha=hashlib.sha256(parsed[2][1].encode()).hexdigest()
    practice_sha=hashlib.sha256(parsed[3][1].encode()).hexdigest()
    lines=['// Code generated by tools/generate_character_querytext.py; DO NOT EDIT.','package characterqueries','',f'const SourceSHA256 = "{hero_sha}"',f'const PetSourceSHA256 = "{pet_sha}"',f'const PresetSourceSHA256 = "{preset_sha}"',f'const PracticeSourceSHA256 = "{practice_sha}"','']
    for name,sql in parts: lines += [f'const {name} = `'+sql.replace('`','`+"`"+`')+'`','']
    return '\n'.join(lines),hero_sha,pet_sha,preset_sha,practice_sha
def main():
    ap=argparse.ArgumentParser(); ap.add_argument('--check',action='store_true'); a=ap.parse_args(); rendered,hsha,psha,ssha,prsha=render()
    if a.check:
        if not out.exists() or out.read_text()!=rendered:
            print(f'CHARACTER QUERYTEXT: FAIL stale {out.relative_to(root)} hero_sha256={hsha} pet_sha256={psha} preset_sha256={ssha} practice_sha256={prsha}'); return 1
        print(f'CHARACTER QUERYTEXT: PASS hero_sha256={hsha} pet_sha256={psha} preset_sha256={ssha} practice_sha256={prsha}'); return 0
    out.parent.mkdir(parents=True,exist_ok=True); out.write_text(rendered); print(f'generated {out.relative_to(root)} hero_sha256={hsha} pet_sha256={psha} preset_sha256={ssha} practice_sha256={prsha}'); return 0
if __name__=='__main__': sys.exit(main())
