#!/usr/bin/env python3
"""Write the inactive mode MID list (I9_MODE_FOUNDATION_V1 MF2) from docs/i9/I9_MODE_SURFACE_V1.json.

Usage: generate_inactive_mids.py [--check]
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SURFACE = ROOT / "docs/i9/I9_MODE_SURFACE_V1.json"
OUTPUT = ROOT / "internal/adapters/stockruntime/inactive_mids_gen.go"
INACTIVE = {"LATER", "INACTIVE_D79", "INACTIVE_SUPERSEDED"}


def render() -> str:
    surface = json.loads(SURFACE.read_text(encoding="utf-8"))
    mids = sorted(row["mid"] for row in surface["mids"] if row["disposition"] in INACTIVE)
    lines = ["// Code generated by tools/generate_inactive_mids.py; DO NOT EDIT.", "package stockruntime", "",
             f"// InactiveModeMIDs are the {len(mids)} LATER, INACTIVE_D79 and INACTIVE_SUPERSEDED MIDs of I9_MODE_SURFACE_V1.",
             "var InactiveModeMIDs = []uint16{"]
    for start in range(0, len(mids), 16):
        lines.append("\t" + ", ".join(str(mid) for mid in mids[start:start + 16]) + ",")
    lines.append("}")
    return "\n".join(lines) + "\n"


def count_drift() -> list[str]:
    """The surface's stored counts are hand-edited beside its rows; any drift is reported, never silently trusted."""
    surface = json.loads(SURFACE.read_text(encoding="utf-8"))
    rows = surface["mids"]
    actual = {"by_disposition": Counter(row["disposition"] for row in rows),
              "active_by_stage": Counter(row["target"] for row in rows if row["disposition"] == "ACTIVE")}
    return [f"counts.{group} {dict(surface['counts'][group])} != rows {dict(actual[group])}"
            for group in actual if Counter(surface["counts"][group]) != actual[group]]


def main() -> None:
    text = render()
    if sys.argv[1:] == ["--check"]:
        drift = count_drift()
        if drift:
            raise SystemExit("I9_MODE_SURFACE_V1 counts disagree with its rows: " + "; ".join(drift))
        if OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{OUTPUT} is stale; run tools/generate_inactive_mids.py")
        return
    OUTPUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
