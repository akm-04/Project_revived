#!/usr/bin/env python3
"""Write the current contract registry for workers: the sealed PassMap's registry plus the contracts the phase
registered since that seal (<phase>/passmap/inputs/CONTRACTS.json), one grep-friendly line per contract with the
absolute path of its document. ops/fleet_queue.py regenerates it before every task.

  contract_index.py           write tmp/fleet_contracts/CONTRACTS_CURRENT.md (and CONTRACT_DOCUMENTS.txt, one document
                              path per line, for grep -l -f style searches) and print the index path
  contract_index.py --check   self-check
"""
import json
import os
import pathlib
import sys
import tempfile

import contract_manifest
import contract_registry
import state

ROOT = pathlib.Path(__file__).resolve().parent.parent
INDEX = ROOT / "tmp" / "fleet_contracts" / "CONTRACTS_CURRENT.md"
DOCUMENTS = INDEX.with_name("CONTRACT_DOCUMENTS.txt")


def document_title(path):
    """Sealed rows carry no title; most documents name their own subject in one of these keys or a first heading."""
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return ""
    if path.suffix != ".json":
        return next((line.lstrip("# ") for line in text.splitlines() if line.startswith("#")), "")
    try:
        document = json.loads(text)
    except json.JSONDecodeError:
        return ""
    if not isinstance(document, dict):
        return ""
    return next((str(document[key]) for key in ("title", "scope", "purpose", "summary") if document.get(key)), "")


def sealed_contracts(generation):
    hot = ROOT / f"work/authority_p{generation}/hot"
    registry = json.loads((hot / "records/contracts.json").read_text(encoding="utf-8"))["contracts"]
    return {identifier: dict(status=entry.get("status"), stage=entry.get("stage"), phases=entry.get("phases") or [],
                             title=entry.get("title") or document_title(hot / entry["document"]), superseded_by=entry.get("superseded_by"),
                             document=hot / entry["document"], source=f"sealed {generation}")
            for identifier, entry in registry.items()}


def pending_contracts(phase_directory):
    inputs = phase_directory / "passmap/inputs"
    path = inputs / "CONTRACTS.json"
    if not path.is_file():
        return {}
    entries = json.loads(path.read_text(encoding="utf-8"))["contracts"]
    return {entry["id"]: dict(status=entry.get("status"), stage=entry.get("stage"), phases=entry.get("phases") or [],
                              title=entry.get("title") or entry.get("note") or "", superseded_by=entry.get("superseded_by"),
                              document=inputs / entry["document"], source="phase inputs")
            for entry in entries}


def unregistered_documents(directory, registered, source, aliases=()):
    """Contract documents the registry does not hold yet: working contracts of the active stage (registered at its
    close) and backend docs that a seal missed. A document counts by the id it declares (contract_registry), never by
    its file name; `aliases` are declared ids the registry holds under a legacy id."""
    found = {}
    for path in sorted(directory.iterdir()) if directory.is_dir() else []:
        identifier = contract_registry.contract_identifier(path) if path.suffix in contract_registry.DOCUMENT_SUFFIXES else None
        if not identifier or identifier in registered or identifier in aliases:
            continue
        document = contract_registry.json_fields(path.read_bytes())
        found[identifier] = dict(status=document.get("status") or document.get("classification") or "UNREGISTERED",
                                 stage=document.get("stage") or "", phases=[], title=document_title(path),
                                 superseded_by=None, document=path, source=source)
    return found


def render(contracts, generation):
    lines = [f"# Current contract registry (sealed PassMap {generation} plus contracts registered since)",
             "",
             "Generated by ops/contract_index.py at every queue task; never edit. Grep it for the system, MID, table or "
             "window you touch and read every IN_FORCE document that matches. A phase-inputs row replaces a sealed row "
             "with the same id. MISSING_DOCUMENT means the document path does not exist: report it. Rows whose source "
             "starts with 'stage working contract' bind the active stage although the PassMap registers them only at "
             "its close; a row whose source starts with 'UNREGISTERED' is a registry gap: use it and report it. The systems "
             "column is the deterministic lookup of ops/contract_manifest.py against the stage integration tree's system map (canonical when none is recorded): * binds "
             "every system, UNRESOLVED means nothing places the contract yet (it still binds whatever it names).",
             "",
             "id | status | stage | phases | systems | title | document | source"]
    for identifier in sorted(contracts):
        entry = contracts[identifier]
        status = entry["status"] if entry["document"].is_file() else f"{entry['status']} MISSING_DOCUMENT"
        if entry["superseded_by"]:
            status += f" superseded_by={entry['superseded_by']}"
        title = " ".join(str(entry["title"]).split())[:200]
        lines.append(f"{identifier} | {status} | {entry['stage']} | {','.join(entry['phases'])} | {entry.get('systems', '')} | {title} | "
                     f"{entry['document']} | {entry['source']}")
    return "\n".join(lines) + "\n"


def write():
    generation, _ = state.sealed_authority()
    phase_directory = ROOT / state.facts()["phase_workspace"]["path"]
    stage = state.facts()["frontier"]["stage"]
    portable = phase_directory / "stages" / stage / "REGISTRY"
    if (portable / "registry.json").is_file():
        registry = json.loads((portable / "registry.json").read_text(encoding="utf-8"))
        contracts = {identifier: dict(status=entry["status"], stage=entry["stage"], phases=entry["phases"],
                                      title=entry["title"] or document_title(portable / entry["document"]),
                                      superseded_by=entry.get("superseded_by"), document=portable / entry["document"],
                                      source=f"{stage} portable registry ({entry['origin']})")
                     for identifier, entry in registry["contracts"].items()}
        tree = contract_manifest.default_tree()
        found = contract_manifest.lookup(portable, tree)
        for identifier, entry in contracts.items():
            placed = found["placed"].get(identifier)
            entry["systems"] = ",".join(sorted(placed)) if placed else ("UNRESOLVED" if identifier in found["unresolved"] else "")
        contracts.update(unregistered_documents(tree / "docs" / phase_directory.name, contracts,
                                                "UNREGISTERED stage tree document", contract_registry.identities(portable, registry)))
        return publish(contracts, registry["base_seal"])
    sealed = sealed_contracts(generation)
    pending = pending_contracts(phase_directory)
    for identifier, entry in pending.items():
        entry["source"] = f"phase inputs, sealed in {generation}" if identifier in sealed else f"phase inputs, new since seal {generation}"
    contracts = {**sealed, **pending}
    contracts.update(unregistered_documents(phase_directory / "stages" / stage / "contracts", contracts,
                                            f"stage working contract {stage}, registered at stage close"))
    contracts.update(unregistered_documents(state.BACKEND / "docs" / phase_directory.name, contracts,
                                            "UNREGISTERED canonical backend document"))
    return publish(contracts, generation)


def publish(contracts, generation):
    INDEX.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", dir=INDEX.parent, delete=False, encoding="utf-8") as handle:
        handle.write(render(contracts, generation))
    os.replace(handle.name, INDEX)
    with tempfile.NamedTemporaryFile("w", dir=INDEX.parent, delete=False, encoding="utf-8") as handle:
        handle.write("".join(f"{contracts[identifier]['document']}\n" for identifier in sorted(contracts)))
    os.replace(handle.name, DOCUMENTS)
    return INDEX


def self_check():
    with tempfile.TemporaryDirectory() as directory:
        present = pathlib.Path(directory) / "a.json"
        present.write_text("{}")
        contracts = {"B_V1": dict(status="IN_FORCE", stage="I9-10", phases=["I9"], title="b", superseded_by=None,
                                  document=pathlib.Path(directory) / "gone.json", source="sealed 1"),
                     "A_V1": dict(status="IN_FORCE", stage="I9-10", phases=["I9"], title="a\nrule", superseded_by=None,
                                  document=present, source="sealed 1")}
        text = render(contracts, 1)
        assert text.index("A_V1 |") < text.index("B_V1 |")
        assert "B_V1 | IN_FORCE MISSING_DOCUMENT |" in text and "| a rule |" in text and "| I9 |  | a rule |" in text
        heading = pathlib.Path(directory) / "c.md"
        heading.write_text("intro\n## Gift boxes\n")
        present.write_text('{"scope": "MID 241"}')
        assert document_title(heading) == "Gift boxes" and document_title(present) == "MID 241"
        present.write_text('{"contract_id": "A_V1"}')
        (pathlib.Path(directory) / "d.json").write_text('{"policy_id": "D_V1", "status": "WORKING"}')
        found = unregistered_documents(pathlib.Path(directory), {"A_V1": contracts["A_V1"]}, "stage")
        assert list(found) == ["D_V1"] and found["D_V1"]["status"] == "WORKING"
        (pathlib.Path(directory) / "gone.json").write_text('{"contract_id": "E_V1"}')
        (pathlib.Path(directory) / "e.md").write_text("Contract-Id: F_V1\n# f\n")
        found = unregistered_documents(pathlib.Path(directory), {"A_V1": contracts["A_V1"], "B_V1": contracts["B_V1"]}, "stage", {"D_V1"})
        assert sorted(found) == ["E_V1", "F_V1"], "a registered file name must not hide a new id"


if __name__ == "__main__":
    if sys.argv[1:] == ["--check"]:
        self_check()
    else:
        print(write())
